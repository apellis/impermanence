package com.neversink.impermanence.domain.session

import com.neversink.impermanence.domain.timer.DaySchedule
import com.neversink.impermanence.model.Day
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.boolean
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File
import java.time.Instant
import java.time.ZoneId

/**
 * Runs the cross-platform bell fixtures in docs/fixtures (generated by scripts/bell_fixtures.py, an
 * independent reference implementation; iOS runs the same files). For each case a session opens at
 * `sessionStart` and runs continuously, driven by its own alarms, until `until`; the bells it rings
 * must be exactly `expectedEvents`.
 */
class SharedBellFixturesTest {
    private val json = Json { ignoreUnknownKeys = true }

    private fun fixturesDir(): File {
        System.getenv("IMPERMANENCE_FIXTURES")?.let { return File(it) }
        var dir: File? = File(System.getProperty("user.dir")).absoluteFile
        while (dir != null) {
            val candidate = File(dir, "docs/fixtures")
            if (candidate.isDirectory) return candidate
            dir = dir.parentFile
        }
        error("docs/fixtures not found above ${System.getProperty("user.dir")}")
    }

    private data class Event(val instant: String, val kind: String, val segmentIndex: Int, val numRings: Int, val soundId: Int)

    @Test
    fun `android matches every shared bell fixture`() {
        val files = fixturesDir().listFiles { f -> f.name.startsWith("bell-") && f.name.endsWith(".json") }!!.sorted()
        assertTrue("expected fixtures, found none", files.isNotEmpty())
        val failures = mutableListOf<String>()
        files.forEach { file ->
            val case = json.parseToJsonElement(file.readText()).jsonObject
            val actual = run(case)
            val expected = case["expectedEvents"]!!.jsonArray.map {
                val o = it.jsonObject
                Event(
                    o["instant"]!!.jsonPrimitive.content,
                    o["kind"]!!.jsonPrimitive.content,
                    o["segmentIndex"]!!.jsonPrimitive.int,
                    o["numRings"]!!.jsonPrimitive.int,
                    o["soundId"]!!.jsonPrimitive.int
                )
            }
            if (actual != expected) {
                failures += "${file.name}:\n  expected $expected\n  actual   $actual"
            }
        }
        assertEquals(failures.joinToString("\n"), 0, failures.size)
        println("Shared bell fixtures passed: ${files.size}")
    }

    private fun run(case: JsonObject): List<Event> {
        val zone = ZoneId.of(case["zone"]!!.jsonPrimitive.content)
        val loop = case["loopDays"]!!.jsonPrimitive.boolean
        val start = Instant.parse(case["sessionStart"]!!.jsonPrimitive.content).toEpochMilli()
        val until = Instant.parse(case["until"]!!.jsonPrimitive.content).toEpochMilli()
        val day = json.decodeFromJsonElement(Day.serializer(), case["day"]!!)

        var session: TimingSession? = TimingSession.DaySession(
            sessionId = "fixture",
            day = day,
            loopDays = loop,
            anchorDate = DaySchedule.initialDate(day, start, zone).toString(),
            handledThroughMillis = start - 1
        )
        val rung = mutableListOf<Event>()
        var now = start
        var guard = 0
        while (session != null && now <= until && guard++ < 100_000) {
            val result = SessionPlanner.process(session, now, zone)
            result.ring?.let { ring ->
                val event = DaySchedule.events(day, DaySchedule.occurrence(day, java.time.LocalDate.parse(ring.key.substringBefore('/')), zone)!!)
                    .first { it.key == ring.key }
                assertEquals("bell rang late in ${case["name"]}", event.atMillis, now)
                rung += Event(
                    Instant.ofEpochMilli(event.atMillis).toString().replace(".000Z", "Z"),
                    if (event.kind == DaySchedule.EventKind.START) "start" else "end",
                    if (event.kind == DaySchedule.EventKind.START) 0 else event.segmentIndex,
                    ring.bell.numRings,
                    ring.bell.soundId
                )
            }
            assertTrue("skipped ${result.skippedKeys} in ${case["name"]}", result.skippedKeys.isEmpty())
            session = result.session
            now = result.nextWakeMillis ?: break
        }
        return rung
    }
}
